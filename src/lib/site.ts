export const absoluteUrl = (path = '/') => `${site.url}${path.startsWith('/') ? path : `/${path}`}`

/** The card generated by app/opengraph-image.tsx */
const defaultOgImage = {
    url: '/opengraph-image',
    width: 1200,
    height: 630,
    alt: `${site.name}, ${site.jobTitle}`,
}

type PageMetaInput = {
    /** Short page title; the layout's template appends " | Sheraz Hussain" */
    title: string
    description: string
    /** Route path, used for the canonical URL and og:url */
    path: string
    /** Overrides the generated Open Graph image */
    image?: { url: string; width?: number; height?: number; alt?: string }
    type?: 'website' | 'profile' | 'article'
}

/**
 * Next.js replaces (does not merge) a parent's openGraph/twitter objects, so every page
 * builds the full set here to keep og:title, og:url and the canonical link in sync.
 */
export function pageMetadata({ title, description, path, image = defaultOgImage, type = 'website' }: PageMetaInput): Metadata {
    const fullTitle = `${title} | ${site.name}`
    return {
        title,
        description,
        alternates: { canonical: path },
        openGraph: {
            type,
            url: path,
            siteName: site.name,
            locale: site.locale,
            title: fullTitle,
            description,
            images: [image],
        },
        twitter: {
            card: 'summary_large_image',
            title: fullTitle,
            description,
            images: [image.url],
        },
    }
}
